"""Generate every file the RTL testbench needs, plus the expected results.

Outputs, all written to ../data :
  chan_mem.hex     channel samples, IN_W bits, two's complement, one word per line,
                   channel-major: all MEM_DEPTH words of channel 0, then channel 1, ...
  delay_int.hex    integer sample address, one word per (point, channel)
  delay_frac.hex   fraction, FRAC_W bits, one word per (point, channel)
  apod.hex         apodisation weights, W_W bits, one per channel
  golden_acc.txt   expected accumulator value per output point, signed decimal
  params.vh        Verilog parameters, so the RTL cannot drift from the data
  scales.txt       the scale factors, needed to rescale the RTL output in MATLAB
"""
import os
import numpy as np
import bf_golden as G

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
os.makedirs(OUT, exist_ok=True)


def twos_hex(v, bits):
    return format(int(v) & ((1 << bits) - 1), "0{}x".format((bits + 3) // 4))


def write_hex(name, values, bits):
    with open(os.path.join(OUT, name), "w") as f:
        for v in np.asarray(values).ravel():
            f.write(twos_hex(v, bits) + "\n")


d = G.build()

# channel memory, channel-major so the RTL can address it as {ch, addr}
mem_cm = d["mem"].T  # [N_CH][MEM_DEPTH]
write_hex("chan_mem.hex", mem_cm, G.IN_W)
write_hex("delay_int.hex", d["di"], 16)
write_hex("delay_frac.hex", d["df"], G.FRAC_W)
write_hex("apod.hex", d["apod"], G.W_W)

with open(os.path.join(OUT, "golden_acc.txt"), "w") as f:
    for v in d["y_fix"]:
        f.write(f"{int(v)}\n")

# $readmemh needs hex; 32-bit two's complement
with open(os.path.join(OUT, "golden_acc_hex.txt"), "w") as f:
    for v in d["y_fix"]:
        f.write(twos_hex(v, G.ACC_W) + "\n")

with open(os.path.join(OUT, "scales.txt"), "w") as f:
    f.write(f"in_scale {d['in_scale']:.12e}\n")
    f.write(f"w_scale  {d['w_scale']:.12e}\n")
    f.write(f"lsb      {d['lsb']:.12e}\n")

with open(os.path.join(OUT, "params.vh"), "w") as f:
    f.write("// generated by gen_vectors.py - do not edit\n")
    for k, v in (("N_CH", G.N_CH), ("IN_W", G.IN_W), ("W_W", G.W_W),
                 ("FRAC_W", G.FRAC_W), ("ACC_W", G.ACC_W),
                 ("N_PTS", G.N_PTS), ("MEM_DEPTH", G.MEM_DEPTH)):
        f.write(f"localparam {k} = {v};\n")

np.savetxt(os.path.join(OUT, "ref_float.txt"), d["y_ref"], fmt="%.12e")
np.savetxt(os.path.join(OUT, "depth_m.txt"), d["zs"], fmt="%.12e")

print(f"wrote {G.MEM_DEPTH*G.N_CH} channel words, "
      f"{G.N_PTS*G.N_CH} delay entries, {G.N_PTS} golden outputs")
print("golden accumulator, points 30-34:", d["y_fix"][30:35].tolist())
pk = int(np.argmax(np.abs(d["y_fix"])))
print(f"hand-check at the peak point p={pk}, channel 0:")
n, fr = int(d["di"][pk, 0]), int(d["df"][pk, 0])
s0, s1 = int(d["mem"][n, 0]), int(d["mem"][n + 1, 0])
s = s0 + ((s1 - s0) * fr >> G.FRAC_W)
print(f"   addr={n} frac={fr}  s0={s0} s1={s1}  ->  s={s}  w={int(d['apod'][0])}"
      f"  ->  product={s*int(d['apod'][0])}")
